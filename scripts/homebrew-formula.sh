#!/bin/sh
# Print Formula/wherebox.rb for a release, from its SHA256SUMS.
# Used by the homebrew job in .github/workflows/release.yml.
#
#   scripts/homebrew-formula.sh <version> <SHA256SUMS> [owner/repo]
set -eu

version=$1
sums=$2
repo=${3:-davidawad/wherebox-cli}
base="https://github.com/$repo/releases/download/v$version"

sha() {
    file="wherebox-$version-$1.tar.gz"
    s=$(awk -v f="$file" '{ sub(/^\*/, "", $2) } $2 == f { print $1 }' "$sums")
    [ -n "$s" ] || { echo "homebrew-formula.sh: $file missing from $sums" >&2; exit 1; }
    echo "$s"
}

# Resolve every checksum first: a failure inside the heredoc below would not
# stop the script.
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_intel=$(sha x86_64-unknown-linux-gnu)

cat <<RUBY
# Generated by the release workflow of https://github.com/$repo; edits here
# are overwritten on the next release.
class Wherebox < Formula
  desc "Personal inventory: what you own, where it is, what it is worth"
  homepage "https://github.com/$repo"
  version "$version"
  license "GPL-3.0-or-later"

  on_macos do
    on_arm do
      url "$base/wherebox-$version-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/wherebox-$version-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end
  on_linux do
    on_arm do
      url "$base/wherebox-$version-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/wherebox-$version-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_intel"
    end
  end

  # Prebuilt release binaries: fsqlite 0.4 needs nightly Rust on x86_64,
  # which Homebrew does not ship.
  def install
    bin.install "wherebox"
    man1.install Dir["man/*.1"]
    bash_completion.install "completions/wherebox.bash" => "wherebox"
    zsh_completion.install "completions/_wherebox"
    fish_completion.install "completions/wherebox.fish"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/wherebox --version")
  end
end
RUBY
